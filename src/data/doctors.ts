// Helper function to parse CSV boolean values
const parseBoolean = (value: string): boolean => {
  if (value === 'OT' || value.includes('Surgery') || value.includes('Emergency')) {
    return true;
  }
  return value.toLowerCase() === 'true';
};

// Helper function to parse qualifications string into array
const parseQualifications = (qualifications: string): string[] => {
  return qualifications.split(',').map(q => q.trim());
};

// Helper function to parse languages string into array
const parseLanguages = (languages: string): string[] => {
  return languages ? languages.split(',').map(l => l.trim()) : [];
};

